	public static string CurrentLanguage
	{
		get
		{
			try
			{
				return LocManager.Instance?.Language ?? Fallback;
			}
			catch
			{
				return Fallback;
			}
		}
	}

	public static string Get(TextId id, params object[] args)
	{
		if (!Table.TryGetValue(CurrentLanguage, out string[]? texts) || (int)id >= texts.Length)
		{
			texts = Table[Fallback];
		}
		string text = texts[(int)id];
		return args.Length == 0 ? text : string.Format(text, args);
	}
